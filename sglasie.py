import io
import os
import sys

# Колко тежи НАШЕТО число в сместа. 1.0 = само нашето (както беше до 25.08),
# 0.0 = само пазарното (измерено най-точно). 0.25 е взетото — виж горе.
def _teglo_ot(sreda=None):
    sreda = os.environ if sreda is None else sreda
    try:
        v = float(str(sreda.get("PREDICT_SGLASIE_TEGLO") or "0.25").strip())
    except (TypeError, ValueError):
        return 0.25
    return min(1.0, max(0.0, v))


TEGLO = _teglo_ot()

# Под тази разлика изобщо не си говорим — двете числа са едно и също нещо
# и смесването само би шумяло. Измерено: при |разлика| под 2 точки
# сбъдваемостта на двете групи е неразличима.
BEZRAZLICHNO = 0.02

# Стените. Карта не бива да обявява сигурност, каквато никой не притежава.
DOLNA, GORNA = 0.05, 0.95


def _chislo(v):
    """Вероятност между 0 и 1, или None при боклук."""
    try:
        p = float(v)
    except (TypeError, ValueError):
        return None
    return p if 0.0 < p < 1.0 else None


def smesi(nasha, pazarna, teglo=None):
    """Числото, което да пише на картата. None само ако нашето е боклук.

    Без пазарна цена връща нашето непокътнато — точно това е случаят на
    тениса на маса и волейбола, тоест на 340 от 728 карти.
    """
    n = _chislo(nasha)
    if n is None:
        return None
    p = _chislo(pazarna)
    if p is None:
        return n
    w = TEGLO if teglo is None else min(1.0, max(0.0, float(teglo)))
    if abs(n - p) < BEZRAZLICHNO:
        return n
    s = w * n + (1.0 - w) * p
    return min(GORNA, max(DOLNA, round(s, 4)))


def obrasta_li(nasha, pazarna, teglo=None):
    """Сменя ли сместа СТРАНАТА на избора. True значи да, картата се обръща.

    🔴 Това е мястото, където се печелят или губят пари, не самото число.
    Мерено на 62 карти, където сме по-смели: обръщането вдига познатите от
    34% на 66%. Затова обръщането е СЛЕДСТВИЕ от сместа, а не отделно
    правило — едно решение, едно място, където може да се сгреши.
    """
    n = _chislo(nasha)
    s = smesi(nasha, pazarna, teglo)
    if n is None or s is None:
        return False
    return (n >= 0.5) != (s >= 0.5)


def sglasni_li(nasha, pazarna):
    """(съгласни, разлика_в_точки). Съгласни значи под прага на безразличие."""
    n, p = _chislo(nasha), _chislo(pazarna)
    if n is None or p is None:
        return (True, 0.0)
    return (abs(n - p) < BEZRAZLICHNO, round(100.0 * (n - p), 1))


def duma(nasha, pazarna):
    """Един ред за картата, или празно. ФАКТ, не лекция и не оправдание.

    Не се пише „моделът ни греши" — това е самобичуване пред читателя и не
    му помага. Не се пише и име на букмейкър: забранено е в целия продукт.
    Пише се само КЪДЕ стои числото спрямо пазара, защото това е проверимо.
    """
    n, p = _chislo(nasha), _chislo(pazarna)
    if n is None or p is None:
        return ""
    sg, raz = sglasni_li(n, p)
    if sg:
        return "📐 пазарът мисли същото"
    if raz > 0:
        return "📐 ние сме по-смели от пазара с %.0f точки" % abs(raz)
    return "📐 пазарът е по-уверен от нас с %.0f точки" % abs(raz)


def selftest():
    ok, bad = 0, []

    def check(ime, uslovie):
        nonlocal ok
        if uslovie:
            ok += 1
        else:
            bad.append(ime)

    # ---------------------------------------------------------- теглото
    check("по подразбиране е 0.25", _teglo_ot({}) == 0.25)
    check("средата може да го смени", _teglo_ot({"PREDICT_SGLASIE_TEGLO": "0.5"}) == 0.5)
    check("боклук пада на подразбирането",
          _teglo_ot({"PREDICT_SGLASIE_TEGLO": "абв"}) == 0.25)
    check("над едно се реже", _teglo_ot({"PREDICT_SGLASIE_TEGLO": "3"}) == 1.0)
    check("под нула се реже", _teglo_ot({"PREDICT_SGLASIE_TEGLO": "-2"}) == 0.0)

    # ---------------------------------------------------------- смесването
    # 🔴 БЕЗ ПАЗАР НИЩО НЕ СЕ МЕНИ. Това пази 340 от 728 карти — тенисът на
    # маса и волейболът нямат никаква пазарна цена по устройство.
    check("без пазарна цена нашето остава", smesi(0.62, None) == 0.62)
    check("боклучава пазарна цена не пипа нашето", smesi(0.62, "абв") == 0.62)
    check("нула не е вероятност", smesi(0.62, 0.0) == 0.62)
    check("единица не е вероятност", smesi(0.62, 1.0) == 0.62)
    check("боклучаво наше число дава празно", smesi(None, 0.5) is None)

    check("сместа тегли КЪМ пазара",
          abs(smesi(0.60, 0.40, 0.25) - 0.45) < 1e-9)
    check("тегло 1 връща само нашето", smesi(0.60, 0.40, 1.0) == 0.60)
    check("тегло 0 връща само пазарното", smesi(0.60, 0.40, 0.0) == 0.40)
    check("при равни числа нищо не се мени", smesi(0.55, 0.55, 0.25) == 0.55)
    check("под прага на безразличие не се пипа",
          smesi(0.550, 0.545, 0.25) == 0.550)
    check("над прага вече се пипа", smesi(0.60, 0.50, 0.25) != 0.60)
    # 🔴 СТЕНИТЕ ВАЖАТ САМО ЗА СМЕСЕНОТО ЧИСЛО, не за преминаващото.
    # Първата ми версия ги налагаше и на двете и два теста паднаха — с право.
    # Преминаващото число е ЧУЖДО: то идва от предсказателя, който си има
    # собствени стени (0.15/0.85, измерени). Нови стени тук биха местили тихо
    # всяка карта без пазар, тоест 340 от 728 — точно това, което този файл
    # обещава да НЕ прави.
    check("горната стена държи смесеното", smesi(0.99, 0.90, 0.9) <= GORNA)
    check("долната стена държи смесеното", smesi(0.01, 0.10, 0.9) >= DOLNA)
    check("преминаващото число НЕ се стеснява", smesi(0.98, None) == 0.98)
    check("и при съгласие не се стеснява", smesi(0.98, 0.97, 0.25) == 0.98)

    # ---------------------------------------------------------- обръщането
    # Истинският случай от дневника: ние 57%, пазарът 39% → смес 43.5% → обръща.
    check("голямото разминаване обръща избора", obrasta_li(0.57, 0.39, 0.25))
    check("и числото минава под половината",
          smesi(0.57, 0.39, 0.25) < 0.5)
    check("малкото разминаване НЕ обръща", not obrasta_li(0.55, 0.52, 0.25))
    check("съгласието не обръща", not obrasta_li(0.62, 0.62, 0.25))
    check("без пазар не обръща", not obrasta_li(0.57, None))
    # 🔴 МУТАЦИЯТА, КОЯТО ТОВА ПАЗИ: ако обръщането се смята по НАШЕТО число
    # вместо по сместа, то никога няма да се случи и целият файл е украса.
    check("обръщането следва СМЕСТА, не нашето",
          obrasta_li(0.57, 0.30, 0.25) and not obrasta_li(0.57, 0.30, 1.0))

    # ---------------------------------------------------------- думите
    check("съгласието се казва", "същото" in duma(0.60, 0.59))
    check("по-смели се казва", "по-смели" in duma(0.60, 0.45))
    check("по-уверен пазар се казва", "по-уверен" in duma(0.45, 0.60))
    check("без пазар няма ред", duma(0.60, None) == "")
    check("точките са цяло число", "15 точки" in duma(0.60, 0.45))
    # Забраненият език не бива да влиза през задната врата.
    for _z in ("bet365", "pinnacle", "коеф", "залож", "букмейкър"):
        check("думата не съдържа " + _z,
              _z not in duma(0.60, 0.45).lower() and _z not in duma(0.45, 0.60).lower())

    _s, _r = sglasni_li(0.60, 0.45)
    check("разликата се връща в точки", not _s and abs(_r - 15.0) < 0.01)
    check("отрицателната разлика си остава отрицателна",
          sglasni_li(0.45, 0.60)[1] < 0)
    check("без числа сме съгласни по подразбиране", sglasni_li(None, 0.5)[0])

    print("САМОПРОВЕРКА НА СЪГЛАСИЕТО: %d наред, %d счупени" % (ok, len(bad)))
    for b in bad:
        print("   счупено: " + b)
    return ok, bad


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    _ok, _bad = selftest()
    sys.exit(1 if _bad else 0)
