def epoh(iso):
    """ISO час -> секунди от епохата. None при липса или боклук.

    Pinnacle пише „2026-09-29T21:00:00Z" в matchups и „...+00:00" в markets.
    И двете са UTC; разчитат се без чужди библиотеки.
    """
    t = str(iso or "").strip().replace(" ", "T")
    if not t:
        return None
    if t.endswith("Z"):
        t = t[:-1]
    opashka = t[10:]
    for znak in ("+", "-"):
        if znak in opashka:
            t = t[:10] + opashka.split(znak)[0]
            break
    if "." in t:
        t = t.split(".")[0]
    for fmt in ("%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M", "%Y-%m-%d"):
        try:
            return float(calendar.timegm(time.strptime(t, fmt)))
        except ValueError:
            continue
    return None


def dni_napred(iso, sega=None):
    """Колко ДНИ напред е този старт. None, ако дата няма."""
    ts = epoh(iso)
    if ts is None:
        return None
    return (ts - float(sega if sega is not None else time.time())) / 86400.0


