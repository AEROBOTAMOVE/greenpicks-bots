def sverka_izhodi(cen0, cen6):
    """[(номер, p0_дом, p6_дом, p6_равен, p6_дом + p6_равен/2)] — чиста функция.

    Числото, с което триизходният пазар беше отхвърлен. Ако последната колона
    се разминава от втората, значи period 6 НЕ е редовното време и цялото
    заглавие на този файл е грешно. Тоест това е проверката, която може да
    обори собственото ми обяснение.
    """
    out = []
    for nomer, tri in sorted((cen6 or {}).items()):
        dve = (cen0 or {}).get(str(nomer))
        if not isinstance(dve, (list, tuple)) or len(dve) < 2:
            continue
        if dve[0] is None or dve[1] is None:
            continue
        if not isinstance(tri, (list, tuple)) or len(tri) < 3:
            continue
        if tri[0] is None or tri[1] is None or tri[2] is None:
            continue
        try:
            s0 = 1.0 / float(dve[0]) + 1.0 / float(dve[1])
            s6 = sum(1.0 / float(x) for x in tri[:3])
            if s0 <= 0 or s6 <= 0:
                continue
            p0 = (1.0 / float(dve[0])) / s0
            p6 = (1.0 / float(tri[0])) / s6
            pr = (1.0 / float(tri[2])) / s6
        except (TypeError, ValueError, ZeroDivisionError):
            continue
        out.append((str(nomer), round(p0, 4), round(p6, 4), round(pr, 4),
                    round(p6 + pr / 2.0, 4)))
    return out


