def index(mach, cen):
    """Списък записи за търсене по имена. САМО от съдимите лиги.

    Тук НЕ се сее прозорецът: ситото казва кой мач става за КАРТА, а
    указателят отговаря на друг въпрос — „каква е цената на тази двойка
    имена". Мач, който вече е започнал, пак има цена, и опресняването я иска.

    🔴 НО БЕЛИЯТ СПИСЪК СЕ СЕЕ И ТУК. Точно това прави моста по прякор
    безопасен: „Rangers" не може да срещне „Kitchener Rangers", защото
    юношеската лига изобщо не влиза в указателя. Виж заглавието.
    """
    out = []
    for nomer, red in sorted((mach or {}).items()):
        if not isinstance(red, (list, tuple)) or len(red) < 2:
            continue
        dom, gost = str(red[0] or ""), str(red[1] or "")
        if not _norm(dom) or not _norm(gost) or _norm(dom) == _norm(gost):
            continue
        liga = str(red[2] or "") if len(red) > 2 else ""
        if not sadima(liga):
            continue
        c = (cen or {}).get(str(nomer))
        cd = c[0] if isinstance(c, (list, tuple)) and len(c) > 0 else None
        cg = c[1] if isinstance(c, (list, tuple)) and len(c) > 1 else None
        if cd is None and cg is None:
            continue
        out.append({"id": str(nomer), "dom": dom, "gost": gost, "liga": liga,
                    "start": str(red[3] or "") if len(red) > 3 else "",
                    "cena_dom": cd, "cena_gost": cg,
                    "nd": _norm(dom), "ng": _norm(gost)})
    return out


def _index_ili_vzemi(ind, mach, cen, pin=None):
    """Указателят: подаденият, или взет от Pinnacle. NEPITAN при отказ."""
    if ind is not None:
        return ind
    if mach is None and cen is None:
        sur = surovi(pin)
        if sur is NEPITAN:
            return NEPITAN
        mach, cen = sur
    return index(mach or {}, cen or {})


def _otgovor(r, nd):
    """Записът, върнат в НАШИЯ ред на страните. None, ако не се разпознава.

    🔴 ДОМАКИНЪТ ПРИ ТЯХ Е НАШИЯТ ДОМАКИН — ПРОВЕРЕНО, НО НЕ ПРЕЗУМИРАНО.
    Мерено днес: Pinnacle пише „away @ home" в същия ред като НХЛ. Въпреки
    това обръщането се проверява и се обявява с флага „obarnat": той влиза в
    дневника и по-късно затварящата цена се взима със същия флаг, без ново
    сверяване на имена. Сгрешена страна значи цената на противника — тихо и с
    вид на успех.
    """
    if nd and nd == r["nd"]:
        obarnat = False
    elif nd and nd == r["ng"]:
        obarnat = True
    else:
        return None
    cd, cg = r["cena_dom"], r["cena_gost"]
    if obarnat:
        cd, cg = cg, cd
    return {"dom": cd, "gost": cg, "nomer": r["id"], "liga": r["liga"],
            "start": r["start"], "obarnat": obarnat}


def _dvoyka_po_nastavka(ind, dom, gost):
    """[(запис, полето на НАШИЯ домакин)] — мачовете, в които ЕДИНИЯТ край
    свършва на прякора на нашия домакин, а ДРУГИЯТ — на прякора на госта.

    🔴 УНИКАЛНОСТТА СЕ ИСКА ОТ ДВОЙКАТА, НЕ ОТ ДУМАТА (поправено 25.08.2026).
    Дотук всеки прякор трябваше да хване ТОЧНО ЕДИН запис на ЦЕЛИЯ указател.
    За лига, в която един отбор играе много мачове, това условие е неизпълнимо
    по устройство: „Boston Bruins“ стои и в мача с Ню Йорк, и в мача с Торонто,
    значи „Bruins“ хващаше ДВА записа и цената мълчеше. Измерено в самия този
    файл: две проверки падаха точно на това — прякорът на Монреал и прякорът
    на Ню Йорк. Мълчанието изглеждаше като предпазливост, а беше слепота.

    Постъпва се като `pinnacle.nameri`, който реши същия въпрос при фамилиите:
    там се сравнява МНОЖЕСТВОТО от двете страни на ЕДИН запис
    (`{_familiya(a), _familiya(b)} == {fd, fg}`), а не колко пъти се среща
    отделната фамилия. Тук е същото, само че с НАСТАВКА вместо фамилия.

    Пази се обаче онова, което струваше „Bury FC“ вместо „Atlanta United“:
    хванат ли се ДВА РАЗНИ мача, се мълчи. Затова се връща списък, а `cena`
    иска дължина 1 — стеснението е върху двойката, не изчезва.

    Под 4 знака не се търси: твърде къс низ е наставка на всичко.
    """
    kd, kg = _norm(dom), _norm(gost)
    if len(kd) < 4 or len(kg) < 4 or kd == kg:
        return []
    out = []
    for r in ind:
        pryamo = r["nd"].endswith(kd) and r["ng"].endswith(kg)
        obratno = r["ng"].endswith(kd) and r["nd"].endswith(kg)
        if pryamo and obratno:
            continue                     # двойката пасва и в двете посоки
        if pryamo:
            out.append((r, "nd"))
        elif obratno:
            out.append((r, "ng"))
    return out


def cena(dom, gost, ind=None, mach=None, cen=None, pin=None):
    """Цената за НАШИТЕ две имена. None = няма. NEPITAN = не можах да питам.

    Два пътя, от строгото към хлабавото, и ДВАТА мълчат при спор:
      1. пълните имена съвпадат (след махане на акцентите — иначе Монреал пада)
      2. НХЛ дава ПРЯКОР („Hurricanes“), Pinnacle дава ПЪЛНО име („Carolina
         Hurricanes“) — двата прякора се търсят като НАСТАВКИ на ДВЕТЕ страни
         на ЕДИН И СЪЩ запис, на РАЗНИ страни, и такъв запис трябва да е
         ТОЧНО ЕДИН на целия указател.

    Условието „точно един" не е предпазливост, а урок: на 25.08.2026 в този
    проект „Atlanta United FC vs Sporting Kansas City" хвана „Bury FC vs
    Lancaster City" по общи думи. Мълчание вместо цената на друг отбор.

    🔴 НО УНИКАЛНОСТТА Е НА ДВОЙКАТА, НЕ НА ДУМАТА. Виж
    `_dvoyka_po_nastavka`: искаше ли се всяка дума поотделно да е уникална,
    отбор с два мача на витрината оставаше без цена — измерено, две проверки
    в този файл падаха точно на това.
    """
    ind = _index_ili_vzemi(ind, mach, cen, pin)
    if ind is NEPITAN:
        return NEPITAN
    nd, ng = _norm(dom), _norm(gost)
    if not nd or not ng or nd == ng:
        return None

    tochni = [r for r in ind if {r["nd"], r["ng"]} == {nd, ng}]
    if len(tochni) == 1:
        return _otgovor(tochni[0], nd)
    if len(tochni) > 1:
        return None                      # спор, който не се разрешава

    dvoyki = _dvoyka_po_nastavka(ind, dom, gost)
    if len(dvoyki) != 1:
        return None                      # нула или спор — и двете са мълчание
    r, pole = dvoyki[0]
    return _otgovor(r, r[pole])


