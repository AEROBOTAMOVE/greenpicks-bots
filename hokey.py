def _bez_akcenti(s):
    """„Montréal" -> „Montreal". Разлага буквата и хвърля знака отгоре.

    🔴 БЕЗ ТОВА ЕДИН ОТ 32-та ОТБОРА Е НЕВИДИМ (измерено 25.08.2026).
    `str.isalnum()` е ИСТИНА за „é", тоест голото свеждане пази акцента и
    „montréalcanadiens" никога не среща „montrealcanadiens". Мълчаливо, с вид
    на „този мач просто го няма". Същият капан като кирилицата при волейбола
    и при тениса.
    """
    t = unicodedata.normalize("NFKD", str(s or ""))
    return "".join(ch for ch in t if not unicodedata.combining(ch))


def _norm(s):
    """Име, сведено до сравнимо: без акценти, малки букви, само букви и цифри."""
    return "".join(ch for ch in _bez_akcenti(s).lower() if ch.isalnum())


