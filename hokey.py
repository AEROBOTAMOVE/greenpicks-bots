#           точно с нищо, а мостът по наставка не пуска под 4 знака. Измерено
#           живо 26.08.2026 върху 32-та отбора: най-късият прякор е ЧЕТИРИ
#           знака („Wild", „Jets"), а всичките 32 съкращения са ТРИ. Тоест
#           прагът 4 разделя двете множества без нито едно изключение.
#   ncaam — ЕСПН дава `location` и там „RIT" е ИСТИНСКОТО име на отбора,
#           не съкращение (измерено: ЕСПН дава „RIT Tigers"/location „RIT",
#           а Pinnacle пише училища от рода на „UAB", „BYU", „TCU"). Затова
#           тук праг НЯМА — общ праг щеше да ИЗЯЖДА верни карти.
#
# Тоест прагът е на СЪДИЯТА, а не на спорта. Без този запис карта „NYR vs
# BUF" излиза в стаята и виси вечно неотсъдена — а в scorer.sport_result
# такава карта тръгва по резервния източник, който отговаря с НИЗ.
MIN_IME = {"nhl": 4}


def prazen_otchet():
    """Отчетът на ситото, преди да е минал един запис."""
    return {"vsichko": 0, "schupeni": 0, "bez_data": 0, "spekulativni": [],
            "nesadimi": {}, "zapochnali": 0, "izvan": 0, "bez_cena": 0,
            "abreviaturi": [], "godni": 0}


def sito(mach, cen, sega=None, dni=None):
    """(годни, отчет). ЧИСТА функция — нито една заявка вътре.

    `dni=None` значи БЕЗ прозорец. `dni=1` значи „днес и утре".

    🔴 РЕДЪТ НА ОТПАДАНЕТО Е ЧАСТ ОТ ОТГОВОРА, точно както при бокса.
    Спекулативните и НЕСЪДИМИТЕ се броят ПРЕДИ прозореца на деня. Обратният
    ред би направил и двете мерки НУЛА винаги: приятелски мач вдругиден щеше
    да пада като „извън прозореца", а не като „няма кой да го отсъди" — тоест
    точно числото, заради което ситото съществува, щеше да казва, че ситото
    не прави нищо.

    Несъдимите се връщат ПОИМЕННО по лига, защото „отпаднаха 5" без имената
    им не може да бъде оспорено от никого.
    """
    s = float(sega if sega is not None else time.time())
    otchet = prazen_otchet()
    godni = []
    for nomer, red in sorted((mach or {}).items()):
        otchet["vsichko"] += 1
        if not isinstance(red, (list, tuple)) or len(red) < 2:
            otchet["schupeni"] += 1
            continue
        dom, gost = str(red[0] or ""), str(red[1] or "")
        liga = str(red[2] or "") if len(red) > 2 else ""
        iso = str(red[3] or "") if len(red) > 3 else ""
        if not _norm(dom) or not _norm(gost) or _norm(dom) == _norm(gost):
            otchet["schupeni"] += 1
            continue
        d = dni_napred(iso, s)
        if d is None:
            otchet["bez_data"] += 1
            continue
        if d > SPEKULA_DNI:
            otchet["spekulativni"].append((dom, gost, round(d, 1), iso))
            continue
        # 🔴 БЕЗ СЪДИЯ НЕ Е КАРТА. Виж „КРЪСТОСВАНЕТО" в заглавието.
        if not sadima(liga):
            klyuch = liga or "(без лига)"
            otchet["nesadimi"][klyuch] = otchet["nesadimi"].get(klyuch, 0) + 1
            continue
        # 🔴 СЪКРАЩЕНИЕ НЕ Е ИМЕ. Виж MIN_IME: „NYR" не може да бъде вързано
        # от НИТО ЕДИН съдия, тоест такава карта е неотсъдима по устройство —
        # точно същият клас като лига без съдия, само че една стъпка по-долу.
        # Броят се ПОИМЕННО и ПРЕДИ прозореца, по същата причина: инак числото
        # щеше да е нула винаги и мярката нямаше да значи нищо.
        _prag = MIN_IME.get(sadiya(liga)[0], 0)
        if len(_norm(dom)) < _prag or len(_norm(gost)) < _prag:
            otchet["abreviaturi"].append((dom, gost, liga))
            continue
        if d * 86400.0 < LEAD_SEK:
            otchet["zapochnali"] += 1
            continue
        if dni is not None and d > float(dni):
            otchet["izvan"] += 1
            continue
        c = (cen or {}).get(str(nomer))
        cd = c[0] if isinstance(c, (list, tuple)) and len(c) > 0 else None
        cg = c[1] if isinstance(c, (list, tuple)) and len(c) > 1 else None
        # И двете цени са условие, не удобство: с една страна маржът не може
        # да се махне, а суровото 1/цена надува пазара с измерените 7.5%.
        if cd is None or cg is None:
            otchet["bez_cena"] += 1
            continue
        pd, pg = chisti_p(cd, cg)
        sad, ime = sadiya(liga)
        godni.append({
            "id": str(nomer), "dom": dom, "gost": gost, "liga": liga,
            "sadiya": sad, "liga_bg": ime,
            "start": iso, "start_ts": epoh(iso), "dni": round(d, 3),
            "cena_dom": cd, "cena_gost": cg, "p_dom": pd, "p_gost": pg,
            # Изричното твърдение на картата. Стои В ЗАПИСА, не в главата на
            # някого: „1" печели и при победа в продълженията, а измереното от
            # пазара равенство в редовното време е 21-23%.
            "period": "цял мач, с продълженията",
        })
    godni.sort(key=lambda x: x["start_ts"])
    otchet["godni"] = len(godni)
    return godni, otchet


def fixtures_s_otchet(sega=None, dni=None, pin=None, mach=None, cen=None):
    """(годни, отчет) или NEPITAN. Тук живее ЕДИНСТВЕНОТО питане към Pinnacle."""
    if mach is None and cen is None:
        sur = surovi(pin)
        if sur is NEPITAN:
            return NEPITAN
        mach, cen = sur
    return sito(mach or {}, cen or {}, sega, dni)


def fixtures(sega=None, dni=None, pin=None, mach=None, cen=None):
    """Предстоящите СЪДИМИ хокейни мачове С ЦЕНА. NEPITAN = не можах да питам.

    🔴 ГОЛОТО `fixtures()` ТРЯБВА ДА РАБОТИ. В този проект вече хванахме
    модул, чиито 45 проверки минаваха, а естественото извикване връщаше None
    ВИНАГИ, защото си строеше указателя от празни речници. Затова: не са ли
    подадени данни, ВЗИМАТ СЕ — и точно този път се изпитва в самопроверката.
    """
    r = fixtures_s_otchet(sega, dni, pin, mach, cen)
    return NEPITAN if r is NEPITAN else r[0]


def krastosvane(mach):
    """{"sadimi": {лига: брой}, "bez_sadiya": {лига: брой}} — чиста функция.

    Отговаря на въпроса, който този файл смята за главния: не „колко мача имат
    цена" и не „колко мача имат резултат", а КОЛКО МАЧА ИМАТ И ДВЕТЕ.
    """
    a, b = {}, {}
    for _n, red in sorted((mach or {}).items()):
        if not isinstance(red, (list, tuple)) or len(red) < 3:
            continue
        liga = str(red[2] or "") or "(без лига)"
        kade = a if sadima(liga) else b
        kade[liga] = kade.get(liga, 0) + 1
    return {"sadimi": a, "bez_sadiya": b}


