def same_bot(a, b):
    """Един и същ бот ли са двата токена? Пред числото преди двоеточието е
    bot id-то — то е публично и не е тайна; самите низове не се печатат."""
    a = (a or "").strip()
    b = (b or "").strip()
    if not a or not b:
        return False
    return a == b or a.split(":")[0] == b.split(":")[0]


