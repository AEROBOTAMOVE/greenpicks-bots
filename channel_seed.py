def api(method, **params):
    """Единственият изход навън. Пуска САМО sendMessage и pinChatMessage.

    Всичко останало се отказва тук — този файл няма право да трие.
    Уважава 429 (parameters.retry_after) и пробва пак.
    """
    if method not in ALLOWED_METHODS:
        print("ОТКАЗ: методът " + str(method) + " е забранен в channel_seed. Триенето е работа на reset.py.")
        return {"ok": False, "error": "method not allowed"}
    url = "https://api.telegram.org/bot" + BOT_TOKEN + "/" + method
    for attempt in range(5):
        data = urllib.parse.urlencode(params).encode()
        try:
            with urllib.request.urlopen(urllib.request.Request(url, data=data), timeout=25) as r:
                return json.loads(r.read())
        except urllib.error.HTTPError as e:
            body = e.read().decode("utf-8", "replace")
            if e.code == 429:
                try:
                    wait = int(json.loads(body).get("parameters", {}).get("retry_after", 5))
                except Exception:
                    wait = 5
                print("  429 при " + method + " — чакам " + str(wait + 1) + " сек. и пробвам пак.")
                time.sleep(wait + 1)
                continue
            print("  " + method + " HTTP " + str(e.code) + " " + body[:160])
            return {"ok": False, "error": body[:160]}
        except Exception as e:
            print("  " + method + " FAIL " + str(e)[:160])
            return {"ok": False, "error": str(e)[:160]}
    return {"ok": False, "error": "429 retries exhausted"}


def clip(text):
    if len(text) <= TG_HARD:
        return text
    return text[:TG_HARD] + NL + "…(отрязано)"


def post(item):
    """Праща един пост в КАНАЛА. Без нишки — каналът не е форум."""
    body = clip(item["text"])
    if DRY:
        print("--- [СУХО] " + item["name"] + " · " + str(len(body)) + " знака"
              + (" · БУТОН: " + item["button"] if item["button"] else "")
              + (" · ЗАКАЧА СЕ" if item["pin"] else "") + " ---")
        print(body)
        print("--- край ---")
        return True
    payload = {"chat_id": CHANNEL_ID, "text": body, "parse_mode": "HTML",
               "disable_web_page_preview": "true"}
    if item["button"]:
        payload["reply_markup"] = json.dumps(
            {"inline_keyboard": [[{"text": item["button"], "url": GROUP_LINK}]]})
    r = api("sendMessage", **payload)
    if not r.get("ok"):
        print("   🔴 не мина: " + str(r)[:160])
        return False
    if item["pin"]:
        mid = r["result"]["message_id"]
        pin = api("pinChatMessage", chat_id=CHANNEL_ID, message_id=mid,
                  disable_notification="true")
        print("   📌 " + ("закачено" if pin.get("ok") else "пратено, но НЕ закачено"))
    return True


def wanted():
    """CHANNEL_SEED_ONLY: празно = всички; иначе списък с запетаи (напр. „1,3“)."""
    raw = (os.environ.get("CHANNEL_SEED_ONLY") or "").strip()
    if len(sys.argv) > 1 and not raw and sys.argv[1].strip().lower() not in ("dry", "сухо", "--dry"):
        raw = sys.argv[1].strip()
    if not raw or raw.lower() in ("all", "всички", "*"):
        return list(POSTS)
    keys = set()
    for part in raw.replace(";", ",").split(","):
        p = part.strip()
        if not p.isdigit():
            print("WARN: пропускам „" + p + "“ — не е номер на пост.")
            continue
        keys.add(int(p))
    out = [it for it in POSTS if it["key"] in keys]
    for k in sorted(keys):
        if not any(it["key"] == k for it in POSTS):
            print("WARN: няма пост номер " + str(k) + ".")
    return out


def selftest():
    """Проверка преди първия байт навън. Грешка тук = не тръгваме."""
    problems = []
    seen = set()
    pins = 0
    for it in POSTS:
        name = it["name"]
        text = it["text"]
        if it["key"] in seen:
            problems.append("повтарящ се номер: " + str(it["key"]))
        seen.add(it["key"])
        if not text.strip():
            problems.append(name + ": празен пост")
        if len(text) > TG_HARD:
            problems.append(name + ": " + str(len(text)) + " знака — над лимита")
        if it["pin"]:
            pins += 1
        # честността е част от продукта: всеки пост носи маркера 18+
        if "18+" not in text:
            problems.append(name + ": липсва маркерът 18+")
        # линкове има САМО в бутона — никакви връзки в текста
        if "http" in text.lower():
            problems.append(name + ": връзка в текста — линкове само през бутона")
        for tag in ("b", "i"):
            if text.count("<" + tag + ">") != text.count("</" + tag + ">"):
                problems.append(name + ": неравни тагове <" + tag + ">")
    if pins != 1:
        problems.append("закачени постове: " + str(pins) + " (трябва точно 1)")
    for m in ALLOWED_METHODS:
        if "delete" in m.lower():
            problems.append("в разрешените методи има триене — забранено")
    return problems


