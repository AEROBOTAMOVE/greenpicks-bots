def clip(text):
    if len(text) <= TG_HARD:
        return text
    return text[:TG_HARD] + NL + "…(отрязано)"


def send(text, thread):
    """Единственият изход навън. Пазачът за стая 4 е ТУК — не по-нагоре."""
    tid = int(thread)
    if tid == HUMAN_ROOM:
        print("ОТКАЗ: стая 4 е на човека-типстер. Ботът не пише там. Никога.")
        return False
    if tid not in KNOWN_ROOMS:
        print("ОТКАЗ: стая " + str(tid) + " не е в картата на групата.")
        return False
    if not CHAT_ID:
        print("Няма CHAT_ID — пропускам.")
        return False
    body = clip(text)
    if DRY:
        print("--- [СУХО] стая " + str(tid) + " · " + str(len(body)) + " знака ---")
        print(body[:400])
        return True
    payload = {"chat_id": CHAT_ID, "text": body, "parse_mode": "HTML",
               "disable_web_page_preview": "true"}
    if tid > 1:
        payload["message_thread_id"] = tid
    url = "https://api.telegram.org/bot" + BOT_TOKEN + "/sendMessage"
    for attempt in range(4):
        data = urllib.parse.urlencode(payload).encode()
        try:
            with urllib.request.urlopen(urllib.request.Request(url, data=data), timeout=25) as r:
                resp = json.loads(r.read())
            if not resp.get("ok"):
                print("TG ERROR:", str(resp)[:200])
                return False
            return True
        except urllib.error.HTTPError as e:
            body_err = e.read().decode("utf-8", "replace")
            if e.code == 429:
                try:
                    wait = int(json.loads(body_err).get("parameters", {}).get("retry_after", 5))
                except Exception:
                    wait = 5
                print("  429 — чакам " + str(wait + 1) + " сек. и пробвам пак.")
                time.sleep(wait + 1)
                continue
            print("TG HTTP", e.code, body_err[:200])
            return False
        except Exception as e:
            print("TG FAIL:", str(e)[:200])
            return False
    return False


def wanted_rooms():
    """SEED_ROOMS: празно или „all“ = всички; иначе списък с запетаи."""
    raw = (os.environ.get("SEED_ROOMS") or "").strip()
    if len(sys.argv) > 1 and not raw:
        raw = sys.argv[1].strip()
    if not raw or raw.lower() in ("all", "всички", "*"):
        return list(ORDER)
    out = []
    for part in raw.replace(";", ",").split(","):
        p = part.strip()
        if not p.isdigit():
            print("WARN: пропускам „" + p + "“ — не е номер на стая.")
            continue
        n = int(p)
        if n == HUMAN_ROOM:
            print("ОТКАЗ: стая 4 е на човека-типстер — не се засява.")
            continue
        if n not in POSTS:
            print("WARN: за стая " + str(n) + " няма съдържание — пропускам.")
            continue
        out.append(n)
    # запазваме смисления ред
    return [r for r in ORDER if r in out]


def selftest():
    """Малка проверка преди първия байт навън. Грешка тук = не тръгваме."""
    problems = []
    if HUMAN_ROOM in POSTS:
        problems.append("стая 4 има съдържание — забранено")
    for room in POSTS:
        if room not in KNOWN_ROOMS:
            problems.append("непозната стая в POSTS: " + str(room))
        if room not in ORDER:
            problems.append("стая " + str(room) + " липсва в ORDER")
        for i, p in enumerate(POSTS[room], 1):
            tag = "стая " + str(room) + " пост " + str(i)
            if len(p) > TG_HARD:
                problems.append(tag + ": " + str(len(p)) + " знака")
            if not p.strip():
                problems.append(tag + ": празен")
            low = p.lower()
            for word in PREACHY:
                if word in low:
                    problems.append(tag + ": поучаващ или рекламен израз „" + word + "“")
    for room in ORDER:
        if room not in POSTS:
            problems.append("ORDER сочи към празна стая " + str(room))
    # Възрастов маркер няма НИКЪДЕ — тонът е прогнози, не инструкции.
    marked = [(r, i) for r in POSTS for i, p in enumerate(POSTS[r], 1) if "18+" in p]
    if marked:
        problems.append("възрастов маркер се появи в: " + str(marked))
    return problems


