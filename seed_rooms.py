def vlei_novite_stai():
    """Долива стаите от rooms_state.json. Връща [(спорт, номер)] или []."""
    try:
        with open(ROOMS_STATE_FILE, encoding="utf-8-sig") as f:
            d = json.load(f)
    except Exception:                                        # noqa: BLE001
        return []
    if not isinstance(d, dict):
        return []
    vleti = []
    for sport, zapis in d.items():
        opis = NOVI_SPORT_NOTE.get(str(sport).strip())
        if not opis or not isinstance(zapis, dict):
            continue
        if str(sport).strip() in ZATVORENI_SPORTOVE:
            continue
        try:
            n = int(zapis.get("thread"))
        except (TypeError, ValueError):
            continue
        # Закованата карта има превес: номер, който вече значи нещо друго, не се
        # презаписва. И стаята на човека не се долива при никакви обстоятелства.
        if n <= 0 or n in KNOWN_ROOMS or n == HUMAN_ROOM:
            continue
        emo, ime, kakvo = opis
        KNOWN_ROOMS.add(n)
        ROOM_NAMES[n] = emo + " " + ime
        POSTS[n] = [sport_note(emo, ime, kakvo)]
        ORDER.append(n)
        vleti.append((str(sport), n))
    return vleti


